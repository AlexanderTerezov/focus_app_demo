                              height: 280,
                              child: CircularProgressIndicator(
                                value: widget.focusSession.isInfinite
                                    ? 0
                                    : progress,
                                strokeWidth: 7,
                                backgroundColor: primaryTextColor.withValues(
                                  alpha: .12,
                                ),
                                valueColor: AlwaysStoppedAnimation<Color>(
                                  ringColor,
                                ),
                              ),
                            ),

                            // Timer text
