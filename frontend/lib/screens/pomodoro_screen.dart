                                    fontSize: 52,
                                    fontWeight: FontWeight.w300,
                                  ),
                                ),

                                const SizedBox(height: 8),

                                Text(
                                  widget.focusSession.isInfinite
                                      ? 'INFINITE'
                                      : '$completedSessions / ${widget.sessionsUntilLongBreak}',
                                  style: TextStyle(
                                    color: secondaryTextColor,
                                    fontSize: 14,
                                  ),
                                ),
                              ],
                            ),
                          ],
                        ),
                      ),

                      // --------------------------------------
                      // END SESSION
                      // --------------------------------------
                      const SizedBox(height: 35),

                      TextButton(
                        onPressed: endSession,
                        child: Text(
                          'END SESSION',
                          style: TextStyle(
                            color: secondaryTextColor,
